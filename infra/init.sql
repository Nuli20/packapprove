do $$ begin if not exists(select 1 from pg_roles where rolname='anon') then create role anon nologin; end if; end $$;
do $$ begin if not exists(select 1 from pg_roles where rolname='authenticated') then create role authenticated nologin; end if; end $$;
do $$ begin if not exists(select 1 from pg_roles where rolname='service_role') then create role service_role nologin bypassrls; end if; end $$;
do $$ begin if not exists(select 1 from pg_roles where rolname='authenticator') then create role authenticator login password 'local-only-postgrest' noinherit; end if; end $$;
grant anon,authenticated,service_role to authenticator;
create schema if not exists auth authorization postgres;
create schema if not exists storage authorization postgres;
create schema if not exists extensions authorization postgres;
create extension if not exists pgcrypto with schema extensions;
create or replace function auth.uid() returns uuid language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid $$;
create or replace function auth.role() returns text language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claim.role',true),''),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'role') $$;
create or replace function auth.jwt() returns jsonb language sql stable as $$ select nullif(current_setting('request.jwt.claims',true),'')::jsonb $$;
grant usage on schema auth to anon,authenticated,service_role;
grant all on schema public to postgres;
grant usage on schema storage,extensions to anon,authenticated,service_role;
alter default privileges in schema storage grant all on tables to service_role;
alter default privileges in schema storage grant all on sequences to service_role;
grant all on all tables in schema storage to service_role;
